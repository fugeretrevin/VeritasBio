class TestSlice1MultiChainInterfaceDDG(unittest.TestCase):
    """Vertical Slice 1: Multi-chain epitope-paratope contact graph & intermolecular ddG_bind."""

    def test_multi_chain_interface_contacts_and_ddg_bind_on_2ybr_complex(self) -> None:
        from workers.spatial_filter import (
            compute_interface_binding_ddg,
            compute_interface_contact_residues,
        )

        interface = compute_interface_contact_residues(
            pdb_path=PDB_2YBR,
            binder_chains=("A", "B"),
            target_chains=("C",),
            cutoff_angstroms=10.0,
        )
        self.assertGreater(len(interface["binder_residues"]), 5)
        self.assertGreater(len(interface["target_residues"]), 5)
        self.assertGreater(len(interface["contact_pairs"]), 5)

        # Pick an actual interface residue on binder chain A
        first_binder_res = interface["binder_residues"][0]
        b_pos = int(first_binder_res["res_seq"])
        b_wt = str(first_binder_res["wt_aa"])

        # Bulky proline/clash disruption at tight interface contact vs favorable/conservative contact
        ddg_disrupt = compute_interface_binding_ddg(
            pdb_path=PDB_2YBR,
            mutation_tuples=[(b_pos, b_wt, "P")],
            binder_chains=("A", "B"),
            target_chains=("C",),
        )
        ddg_favorable = compute_interface_binding_ddg(
            pdb_path=PDB_2YBR,
            mutation_tuples=[(b_pos, b_wt, "Y")],
            binder_chains=("A", "B"),
            target_chains=("C",),
        )
        self.assertGreater(ddg_disrupt, ddg_favorable)


class TestSlice2ESM1280ReadoutAdapter(unittest.TestCase):
    """Vertical Slice 2: 1280-Dim ESM-2 embedding Ridge/SVD readout adapter overcoming zero-shot conservation bias."""

    def test_esm_readout_adapter_overcomes_zeroshot_conservation_bias_on_nonnatural_substrate(self) -> None:
        import numpy as np
        from scipy.stats import spearmanr
        from controller.gatekeeper import Variant
        from workers.math_worker import SequenceReadoutAdapter

        wt_seq = "MSKGEELFTGVVPILVELDGDVNGHKFSVSGEGEGDATYGKLTLKFICTTGKLPVPWPTLVTTFSYGVQCFSRYPDHMKQHDFFKSAMPEGYVQERTIFFKDDGNYKTRAEVK"
        aas = ["A", "V", "I", "L", "M", "F", "Y", "W", "S", "T", "Q", "N", "K", "R", "D", "E"]
        # Generate 32 variants at active-site positions 64 and 65
        variants = []
        for a1 in aas[:8]:
            for a2 in aas[:4]:
                muts = []
                if a1 != wt_seq[63]:
                    muts.append(f"{wt_seq[63]}64{a1}")
                if a2 != wt_seq[64]:
                    muts.append(f"{wt_seq[64]}65{a2}")
                if muts:
                    variants.append(Variant(notation=":".join(muts)))

        # Shuffle before splitting. `variants` is generated by a nested loop over
        # amino acids, so an ordered split puts whole residue identities entirely
        # in train or entirely in test - an extrapolation task under distribution
        # shift, not a held-out evaluation. Measured on the ordered split the
        # score moved erratically and got *worse* with more calibration data
        # (0.49 -> 0.20 -> -0.22), which told us about the split, not the model.
        shuffle_rng = np.random.RandomState(13)
        order = shuffle_rng.permutation(len(variants))
        variants = [variants[i] for i in order]

        seqs = [v.apply_to(wt_seq) for v in variants]
        adapter = SequenceReadoutAdapter(feature_dim=128, latent_dim=16, ridge_alpha=1.0)
        emb = adapter.embed_sequences(seqs, wt_sequence=wt_seq)
        self.assertEqual(emb.shape, (len(seqs), adapter.feature_dim))
        # Position encoding must spread across banks rather than aliasing a few slots.
        self.assertGreaterEqual(adapter.n_position_banks, 12)

        # Ground-truth non-natural catalytic fitness: favors branched hydrophobics (I, V, L) at 64/65,
        # whereas naive zero-shot evolutionary conservation penalizes them!
        rng = np.random.RandomState(7)
        true_w = rng.randn(adapter.feature_dim) * 0.15
        true_y = emb @ true_w + 1.5
        zeroshot_conservation = -0.8 * true_y + rng.normal(0, 0.05, size=len(seqs))

        rho_zeroshot, _ = spearmanr(zeroshot_conservation[12:], true_y[12:])
        self.assertLess(rho_zeroshot, 0.0)

        # Calibrate readout head on just 12 wet-lab variants
        adapter.fit(seqs[:12], true_y[:12], wt_sequence=wt_seq, embeddings=emb[:12])
        preds_heldout = adapter.predict(
            seqs[12:],
            wt_sequence=wt_seq,
            zero_shot_priors=zeroshot_conservation[12:],
            embeddings=emb[12:],
        )
        rho_calibrated, _ = spearmanr(preds_heldout, true_y[12:])
        self.assertGreater(rho_calibrated, 0.65)
        latent_proj = adapter.project_latent(seqs[12:], wt_sequence=wt_seq, embeddings=emb[12:])
        self.assertEqual(latent_proj.shape[0], len(seqs) - 12)
        self.assertLessEqual(latent_proj.shape[1], 16)


class TestSlice3KrigingBelieverAsyncBatchSelection(unittest.TestCase):
    """Vertical Slice 3: Kriging-believer GP conditioning on in-flight SpeculativeEvidence prevents duplicate sampling."""

    def test_select_top_variants_conditions_on_speculative_evidence_with_zero_overlap(self) -> None:
        from controller.prompts import ResidueCluster, SearchStrategy
        from workers.math_worker import select_top_variants

        wt_seq = (
            "MSKGEELFTGVVPILVELDGDVNGHKFSVSGEGEGDATYGKLTLKFICTTGKLPVPWPTLVTTFSYGVQCFSRYPDHMKQHDFFKSAMPEGYVQERTIFFKDDGNYKTRAEVK"
            "FEGDTLVNRIELKGIDFKEDGNILGHKLEYNYNSHNVYIMADKQKNGIKVNFKIRHNIEDGSVQLADHYQQNTPIGDGPVLLPDNHYLSTQSALSKDPNEKRDHMVLLEFVTAAGITHGMDELYK"
        )
        strategy = SearchStrategy(
            target_protein="avGFP",
            target_accession="P42212",
            hypothesis="Explore chromophore contact pocket",
            target_clusters=[
                ResidueCluster(cluster_id="chromophore_shell", positions=[64, 65, 203], rationale="Synergy")
            ],
            forbidden_positions=[67],
            max_mutation_depth=2,
        )

        # Round N selects 8 variants
        batch_round_n = select_top_variants(
            strategy=strategy,
            wt_sequence=wt_seq,
            evidence=[],
            batch_size=8,
            random_seed=42,
        )
        in_flight_seqs = {v.apply_to(wt_seq) for v in batch_round_n.variants}
        in_flight_notations = {v.notation for v in batch_round_n.variants}
        speculative_rows = [
            {"variant_sequence": v.apply_to(wt_seq), "fantasy_score": m, "is_provisional": 1}
            for v, m in zip(batch_round_n.variants, batch_round_n.predicted_means)
        ]

        # Round N+1 runs asynchronously while Round N is incubating in the wet-lab
        batch_round_n_plus_1 = select_top_variants(
            strategy=strategy,
            wt_sequence=wt_seq,
            evidence=[],
            speculative_evidence=speculative_rows,
            batch_size=8,
            random_seed=42,
        )
        next_notations = {v.notation for v in batch_round_n_plus_1.variants}
        next_seqs = {v.apply_to(wt_seq) for v in batch_round_n_plus_1.variants}

        self.assertEqual(len(in_flight_notations.intersection(next_notations)), 0)
        self.assertEqual(len(in_flight_seqs.intersection(next_seqs)), 0)


class TestSlice4DoseResponseKineticsAndSynthesisCost(unittest.TestCase):
    """Vertical Slice 4: 4PL IC50/Kd curve fitting, Michaelis-Menten v0 kinetics & wet-lab synthesis cost gate."""

    def test_4pl_dose_response_and_kinetics_and_synthesis_cost_estimator(self) -> None:
        from controller.gatekeeper import estimate_wetlab_synthesis_cost
        from scripts.ingest_plate_data import (
            fit_dose_response_4pl,
            fit_michaelis_menten_kinetics,
        )

        # 1. Deterministic wet-lab DNA synthesis + robotic assay cost model
        cost_linear = estimate_wetlab_synthesis_cost(
            variant_count=10,
            sequence_length_aa=238,
            synthesis_format="linear_fragment",
            replicates=3,
        )
        cost_clonal = estimate_wetlab_synthesis_cost(
            variant_count=10,
            sequence_length_aa=238,
            synthesis_format="twist_clonal_gene",
            replicates=3,
        )
        self.assertEqual(cost_linear["basepairs_per_variant"], 238 * 3 + 60)
        self.assertGreater(cost_linear["total_wetlab_cost_usd"], 500.0)
        self.assertGreater(cost_clonal["total_wetlab_cost_usd"], cost_linear["total_wetlab_cost_usd"])

        # 2. 4-Parameter Logistic (4PL) dose-response curve fit (true IC50 = 12.5 nM, Hill = 1.2)
        concs = [0.1, 0.5, 2.0, 5.0, 12.5, 30.0, 100.0, 500.0]
        true_ic50 = 12.5
        responses = [5.0 + (95.0 - 5.0) / (1.0 + (c / true_ic50) ** 1.2) for c in concs]
        fit_4pl = fit_dose_response_4pl(concs, responses)
        self.assertAlmostEqual(fit_4pl["ic50"], true_ic50, delta=1.5)
        self.assertGreater(fit_4pl["r_squared"], 0.99)
        self.assertGreater(fit_4pl["potency_variance"], 0.0)

        # 3. Michaelis-Menten initial velocity v0 with late-stage substrate depletion plateau
        # Linear phase: 0 to 60s at slope 0.015 Abs/s, then plateau at 90s, 120s
        times = [0.0, 15.0, 30.0, 45.0, 60.0, 90.0, 120.0]
        abs_vals = [0.10, 0.325, 0.55, 0.775, 1.00, 1.04, 1.05]
        kin = fit_michaelis_menten_kinetics(times, abs_vals)
        self.assertAlmostEqual(kin["initial_slope_abs_per_sec"], 0.015, delta=0.0015)
        self.assertGreater(kin["r_squared"], 0.99)
        self.assertEqual(kin["linear_points_used"], 5)

        # 4. REST API /api/campaign/ingest-curves fold-potency ingestion
        import tempfile
        from fastapi.testclient import TestClient
        from server import app

        with tempfile.TemporaryDirectory() as tmpdir:
            db_path = Path(tmpdir) / "test_curves.db"
            client = TestClient(app)
            wt_responses = [5.0 + (95.0 - 5.0) / (1.0 + (c / 50.0) ** 1.1) for c in concs]
            lead_responses = [5.0 + (95.0 - 5.0) / (1.0 + (c / 10.0) ** 1.2) for c in concs]
            resp = client.post(
                "/api/campaign/ingest-curves",
                json={
                    "curve_type": "dose_response_4pl",
                    "target_accession": "P42212",
                    "db_path": str(db_path),
                    "series": [
                        {"mutations": "WT", "x_values": concs, "y_values": wt_responses},
                        {"mutations": "S65T:T203Y", "x_values": concs, "y_values": lead_responses},
                    ],
                },
            )
            self.assertEqual(resp.status_code, 200, resp.text)
            data = resp.json()
            self.assertEqual(data["variants_ingested"], 2)
            # S65T:T203Y has 5x lower IC50 (10 nM vs 50 nM WT) -> ~5.0x normalized potency score
            self.assertAlmostEqual(data["fitted_curves"][1]["normalized_score"], 5.0, delta=0.5)


if __name__ == "__main__":
    unittest.main()
